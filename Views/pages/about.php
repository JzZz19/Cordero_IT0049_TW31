<section class="card prose-card">
    <h2>How the application works</h2>
    <p>
        A route matches the URL requested by the browser and selects a controller
        method. The controller prepares the required data and passes it to a view.
        The view generates the HTML response displayed by the browser.
    </p>
    <p>
        This first version does not use a database. Customer and user records are
        stored temporarily in static PHP arrays inside their controllers.
    </p>
</section>

